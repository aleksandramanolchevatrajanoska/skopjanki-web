export type Locale = "en" | "mk";
export const dicts: Record<Locale, Dict> = { en, mk };

export async function getLocale(userLocale?: string | null): Promise<Locale> {
  const c = (await cookies()).get("lang")?.value;
  if (c === "mk" || c === "en") return c;
  return userLocale === "mk" ? "mk" : "en";
}

export async function getT(userLocale?: string | null) {
  const locale = await getLocale(userLocale);
  return { t: dicts[locale], locale };
}

